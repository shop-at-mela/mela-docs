"""Build config/ledger.yaml from social/log/*.yaml. Best effort: the logs are not a complete
record of the account, so every entry says how sure we are. Humans correct it in
config/ledger_overrides.yaml (times, extra posts) and config/post_tags.yaml (people_present)."""
from __future__ import annotations

import datetime as dt
import re
from pathlib import Path
from typing import Any, Optional
from urllib.parse import urlparse

import yaml

CONFIRMED = ("posted", "published", "live")
LOGGED = CONFIRMED + ("scheduled", "partially_scheduled", "live_ig_pinterest_partial")


def _iso(v: Any) -> Optional[str]:
    if v is None:
        return None
    if isinstance(v, dt.datetime):
        return v.isoformat()
    if isinstance(v, dt.date):
        return v.isoformat()
    return str(v)


def _format(fmt: Any) -> str:
    f = str(fmt or "").lower()
    if "reel" in f:
        return "reel"
    if "image" in f and "carousel" not in f:
        return "image"
    return "carousel"


def _brands(d: dict, ig: dict, slugs: set[str]) -> list[str]:
    slug = str(d.get("brand_slug") or "")
    if slug and not slug.startswith("_"):
        return [slug]
    dest = urlparse(str(ig.get("destination") or ""))
    parts = [x for x in dest.path.split("/") if x]
    if len(parts) >= 2 and parts[0] == "brands":
        return [parts[1]]
    return []


def build(log_dir: Path, overrides: dict, slug_map: dict[str, str]) -> list[dict]:
    posts: list[dict] = []
    for f in sorted(log_dir.glob("*/*.yaml")):
        if f.name == "CAMPAIGN_TEMPLATE.yaml" or f.parent.name == "_pending":
            continue
        try:
            d = yaml.safe_load(f.read_text(encoding="utf-8"))
        except yaml.YAMLError:
            continue
        if not isinstance(d, dict) or not isinstance(d.get("instagram"), dict):
            continue
        ig = d["instagram"]
        status = str(d.get("status") or "").split()[0] if d.get("status") else ""
        if not (status in LOGGED or (not status and ig.get("submission_id"))):
            continue
        post_id = f"{f.parent.name}/{f.stem}"
        when = _iso(ig.get("scheduled_time") or ig.get("scheduled_utc") or ig.get("scheduledTime") or d.get("date_posted"))
        brands = [slug_map.get(b, b) for b in _brands(d, ig, set())]
        media: list[dict] = []
        for prod in ig.get("products") or []:
            media.append({"kind": "brand_asset", "brand": brands[0] if brands else "unknown",
                          "file": prod.get("source_photo") or prod.get("image_url") or prod.get("name", "?")})
        if not media:
            media.append({"kind": "owned_asset", "date": _iso(d.get("date_posted")) or "unknown",
                          "source": "Mela text card (mela-docs/social/templates)", "file": "education or text card"})
        entry = {
            "id": post_id, "status": "live" if status in CONFIRMED else "scheduled",
            "format": _format(d.get("format")), "posted_at": when,
            "brands": brands, "caption": ig.get("caption") or "", "media": media,
            "people_present": None, "pinned": False,
            "source": f"log/{f.parent.name}/{f.name}", "confirmed": status in CONFIRMED,
        }
        entry.update(overrides.get(post_id, {}))
        posts.append(entry)
    for post_id, extra in overrides.items():
        if extra.get("add") and not any(p["id"] == post_id for p in posts):
            e = {k: v for k, v in extra.items() if k != "add"}
            e["id"] = post_id
            posts.append(e)
    return posts


def write(path: Path, posts: list[dict]) -> None:
    header = ("# Generated by `python3 -m post_validators import-ledger`. Do not hand edit.\n"
              "# Corrections go in ledger_overrides.yaml. people_present tags go in post_tags.yaml.\n"
              "# Built from social/log, which is NOT a complete record of the Instagram account.\n")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(header)
        yaml.safe_dump({"posts": posts}, fh, sort_keys=False, allow_unicode=True, width=100)
